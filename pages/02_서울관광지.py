# 4. 서울 지도 만들기
# =========================================

st.subheader("📍 서울 관광지 지도")

seoul_map = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=12,
    tiles="OpenStreetMap"
)

for place in PLACES:

    popup_html = f"""
    <div style="width:220px">
        <h4>
            {place['emoji']} {place['rank']}.
            {place['name']}
        </h4>
        <p>{place['description']}</p>
    </div>
    """

    folium.Marker(
        location=[
            place["lat"],
            place["lon"]
        ],
        tooltip=place["name"],
        popup=folium.Popup(
            popup_html,
            max_width=280
        ),
        icon=folium.DivIcon(
            html=f"""
            <div style="
                background:#2563eb;
                color:white;
                border:2px solid white;
                border-radius:50%;
                width:30px;
                height:30px;
                line-height:26px;
                text-align:center;
                font-weight:bold;
                font-size:14px;
            ">
                {place['rank']}
            </div>
            """,
            icon_size=(30, 30),
            icon_anchor=(15, 15)
        )
    ).add_to(seoul_map)

# 관광지 전체가 보이도록 설정

bounds = [
    [p["lat"], p["lon"]]
    for p in PLACES
]

seoul_map.fit_bounds(
    bounds,
    padding=(25, 25)
)

st_folium(
    seoul_map,
    use_container_width=True,
    height=560,
    returned_objects=[]
)

